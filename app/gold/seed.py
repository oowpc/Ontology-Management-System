def seed_gold(db: Session):
    """空库时预置 13 篇 + 泳道；已有数据则跳过（幂等）。"""
    if (db.scalar(select(func.count()).select_from(GoldArticle)) or 0) == 0:
        for code, domain, group, target in ARTICLES:
            db.add(GoldArticle(code=code, title=f"{domain}领域·{code}", domain=domain,
                               group_name=group, ke_target=target, created_by="seed"))
    if (db.scalar(select(func.count()).select_from(GoldScheduleCell)) or 0) == 0:
        for day, slot, group, task, acode in SCHEDULE:
            db.add(GoldScheduleCell(day_index=day, slot=slot, group_name=group,
                                    task=task, article_code=acode, status="planned"))
    db.commit()
